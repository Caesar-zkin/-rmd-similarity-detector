source("R/code.R", encoding = "UTF-8")
source("R/code-local.R", encoding = "UTF-8")
count <- 0L
check <- function(ok, label) {
  if (!isTRUE(ok)) stop(label)
  count <<- count + 1L; cat("PASS", label, "\n")
}
fails <- function(expr, label) check(inherits(try(force(expr), silent = TRUE), "try-error"), label)
doc <- function(code, id = "document") parse_rmd_text(paste0("```{r}\n", code, "\n```"), file_id = id)
core_a <- "values<-c(1,2,3)\ncenter<-mean(values)\nprint(center)"
core_b <- "nums<-c(1,2,3)\nextra<-0\navg<-mean(nums)\nprint(avg)"
a <- doc(paste0("irrelevant<--99\n", core_a, "\ntailvalue<-99"), "A")
b <- doc(core_b, "B")
s <- prepare_code_statements(doc(core_a))
check(nrow(s) == 3L && sum(s$token_count) == 20L, "top-level statements and token counts")
check(identical(s$start_line, c(2L, 3L, 4L)), "statement global lines")
for (i in seq_len(nrow(s))) {
  tokens <- s$tokens[[i]]
  source_doc <- doc(core_a)
  check(identical(substring(source_doc$source, tokens$start_offset, tokens$end_offset), tokens$text), "statement source token reconstruction")
}
parsed <- tokenize_r_code(core_a)
check(length(parsed$statements) == 3L && parsed$statement_status == "ok", "parse graph root partition")
fails(tokenize_r_code(core_a, max_statements = 1L), "per-unit statement limit")
r <- analyze_code_pair_local(a, b)
check(r$status == "ok" && nrow(r$matches) == 1L, "local renamed match found")
check(r$matches$method == "renamed" && r$matches$matched_statements == 3L, "three statements share mapping")
check(r$matches$matched_tokens == 20L && r$matches$skipped_tokens == 3L, "inserted statement tokens excluded")
check(r$matches$skipped_statements == 1L && isTRUE(all.equal(r$matches$alignment_ratio, 20 / 23)), "alignment ratio counts skipped tokens")
check(identical(r$matches$variable_map[[1L]], data.frame(a = c("values", "center"), b = c("nums", "avg"))), "mapping independent of unrelated prefix definitions")
check(identical(r$coverage$comparable_tokens, c(27L, 23L)), "all comparable tokens include unmatched prefix and suffix")
check(all(r$coverage$matched_tokens == 20L), "matched token union count")
check(isTRUE(all.equal(r$coverage$coverage, c(20 / 27, 20 / 23))), "separate directional structural coverage")
check(all(r$lexical_coverage$coverage == 0), "lexical coverage kept separate from renaming")
check(r$matches$start_line_a == 3L && r$matches$end_line_a == 5L, "cross-position A location")
check(identical(r$matches$statement_pairs[[1L]]$start_line_b, c(2L, 4L, 5L)), "skipped B statement absent from pair list")
skipped <- match(r$matches$skipped_statements_b[[1L]], r$statements_b$statement_id)
check(r$statements_b$content[skipped] == "extra<-0", "explicit skipped statement lookup")
check(!any(r$statements_b$tokens[[skipped]]$start_offset %in% r$matches$token_starts_b[[1L]]), "skipped token positions not covered")
check(nrow(analyze_code_pair_local(a, b, max_skips = 0L)$matches) == 0L, "zero insertion budget")
check(nrow(analyze_code_pair_local(a, b, min_tokens = 21L)$matches) == 0L, "minimum matched-token threshold")
reverse <- analyze_code_pair_local(b, a)
check(reverse$matches$matched_tokens == 20L && reverse$matches$skipped_tokens == 3L, "deletion symmetry")
check(identical(reverse$coverage$matched_tokens, r$coverage$matched_tokens), "reverse token counts")
check(isTRUE(all.equal(reverse$coverage$coverage, rev(r$coverage$coverage))), "reverse directional coverage")
copy <- "x<-1\ny<-2\nprint(x+y)"
overlap <- analyze_code_pair_local(doc(copy), doc(copy), window_tokens = 9L, min_tokens = 3L)
check(nrow(overlap$windows_a) == 2L && nrow(overlap$matches) == 2L, "overlapping statement windows")
check(sum(overlap$matches$matched_tokens) > overlap$coverage$matched_tokens[1L], "overlapping evidence is not simply summed")
check(all(overlap$coverage$coverage == 1) && all(overlap$lexical_coverage$coverage == 1), "overlap counted once in coverage")
check(all(overlap$matches$method == "lexical"), "identity renaming not duplicate evidence")
repeated <- analyze_code_pair_local(doc(paste(copy, copy, sep = "\n")), doc(copy), min_tokens = 3L, min_statements = 2L)
check(nrow(repeated$matches) == 2L, "repeated source alignments retained")
check(all(repeated$coverage$coverage == 1) && repeated$coverage$matched_tokens[1L] == 24L && repeated$coverage$matched_tokens[2L] == 12L, "repeated target positions counted once")
oversize <- make_code_windows(prepare_code_statements(doc("print(c(1,2,3,4))")), window_tokens = 2L)
check(nrow(oversize) == 1L && oversize$oversize && length(oversize$statement_indices[[1L]]) == 1L, "long statement remains atomic")
all_indices <- sort(unique(as.integer(unlist(overlap$windows_a$statement_indices))))
check(identical(all_indices, seq_len(nrow(overlap$statements_a))), "window tail coverage")
boundary <- analyze_code_pair_local(doc("x<-1\n-y"), doc("x<-1-y"), min_tokens = 1L)
check(nrow(boundary$matches) == 0L && all(boundary$coverage$coverage == 0), "expression boundaries prevent flattened token false match")
semis <- analyze_code_pair_local(doc("x<-1;y<-2"), doc("x <- 1\ny <- 2"), min_tokens = 1L)
check(all(semis$coverage$comparable_tokens == 6L) && all(semis$coverage$coverage == 1), "semicolons and layout excluded from coverage")
inconsistent <- analyze_code_pair_local(doc("x<-1\ny<-x+2\nprint(y)"), doc("a<-1\nb<-a+2\nprint(a)"), min_tokens = 1L, min_statements = 3L)
check(nrow(inconsistent$matches) == 0L, "one mapping across all matched statements")
collision <- analyze_code_pair_local(doc("x<-1\ny<-2\nprint(x+y)"), doc("a<-1\na<-2\nprint(a+a)"), min_tokens = 1L, min_statements = 3L)
check(nrow(collision$matches) == 0L, "different source locals cannot merge")
members <- analyze_code_pair_local(doc("value<-1\nout<-data$value+value"), doc("n<-1\nres<-data$value+n"), min_tokens = 1L, min_statements = 2L)
check(members$matches$method == "renamed", "member fields preserved within local renaming")
for (pair in list(c("x<-incoming+1", "a<-other+1"), c("x<-mean(c(1,2))", "a<-sum(c(1,2))"),
    c("x<-'a.csv'", "a<-'b.csv'"), c("x<-1", "a<-2"))) {
  mismatch <- analyze_code_pair_local(doc(pair[1L]), doc(pair[2L]), min_tokens = 1L)
  check(nrow(mismatch$matches) == 0L, "external names calls strings and numbers retained")
}
changed_a <- doc("x<-c(1,2)\nchanged<-sum(x)\ny<-x+1\nprint(y)")
changed_b <- doc("a<-c(1,2)\nother<-mean(a)\nb<-a+1\nprint(b)")
check(nrow(analyze_code_pair_local(changed_a, changed_b, min_tokens = 1L, min_statements = 3L)$matches) == 0L, "changed statement needs two-sided skip budget")
changed <- analyze_code_pair_local(changed_a, changed_b, min_tokens = 1L, min_statements = 3L, max_skips = 2L)
check(changed$matches$matched_statements == 3L && changed$matches$skipped_statements == 2L, "replacement represented as two skipped statements")
check(changed$matches$matched_tokens == 17L && changed$matches$skipped_tokens == 12L, "changed statements wholly excluded")
scope <- "f<-function(x){z<-x+1;z*2}"
limited <- analyze_code_pair_local(doc(scope), doc(scope), min_tokens = 1L)
check(limited$status == "limited" && all(limited$matches$method == "lexical") && all(limited$coverage$coverage == 1), "complex scope supports lexical-only matching")
check(nrow(prepare_code_statements(doc(scope))) == 1L, "function body not split into independent top-level statements")
separate <- parse_rmd_text("```{r}\nx<-1\n```\n\n```{r}\ny<-2\n```")
cross_units <- analyze_code_pair_local(separate, doc("x<-1\ny<-2"), min_tokens = 1L, min_statements = 2L)
check(nrow(cross_units$matches) == 0L, "local path cannot cross code units")
broken <- analyze_code_pair_local(doc("x<-"), doc(copy), min_tokens = 1L)
check(broken$status == "limited" && is.na(broken$coverage$coverage[1L]), "failed parse is not zero coverage")
missing <- analyze_code_pair_local(parse_rmd_text("只有正文"), doc(copy), min_tokens = 1L)
check(missing$status == "not_applicable" && is.na(missing$coverage$coverage[1L]), "missing code side")
check(identical(names(missing$matches), names(r$matches)), "stable empty local-match schema")
comment_only <- analyze_code_pair_local(doc("# explanation"), doc("# explanation"), min_tokens = 1L)
check(comment_only$status == "insufficient_content" && all(is.na(comment_only$coverage$coverage)), "comments excluded from code denominator")
comments <- analyze_code_pair_local(doc("x<-1 # first"), doc("x<-1 # second"), min_tokens = 1L)
check(all(comments$coverage$comparable_tokens == 3L) && all(comments$coverage$coverage == 1), "comments neither code tokens nor coverage")
stop_result <- analyze_code_pair_local(doc("stop('must not run')"), doc("stop('must not run')"), min_tokens = 1L)
check(all(stop_result$coverage$coverage == 1), "local pipeline never evaluates submitted calls")
original_a <- a; original_b <- b; invisible(analyze_code_pair_local(a, b))
check(identical(a, original_a) && identical(b, original_b), "input documents unchanged")
for (side in c("a", "b")) {
  source_doc <- if (side == "a") a else b
  starts <- r$matches[[paste0("token_starts_", side)]][[1L]]
  ends <- r$matches[[paste0("token_ends_", side)]][[1L]]
  check(length(starts) == 20L && length(ends) == 20L && all(starts <= ends), "covered token position vectors")
  text <- substring(source_doc$source, starts, ends)
  all_tokens <- do.call(rbind, lapply(r[[paste0("code_", side)]]$details, function(d) d$tokens))
  check(identical(text, all_tokens$text[match(starts, all_tokens$start_offset)]), "covered token reconstruction")
}
for (name in c("window_tokens", "window_statements", "min_tokens", "min_statements", "max_statements", "max_windows",
    "max_candidates", "max_seed_pairs", "max_states", "max_results", "max_token_work")) {
  for (bad in list(0, -1, 1.5, Inf, NA_real_, "2")) {
    args <- list(doc_a = a, doc_b = b); args[[name]] <- bad
    fails(do.call(analyze_code_pair_local, args), paste("invalid", name))
  }
}
for (bad in list(-1, 1.5, Inf, NA_real_, "2")) fails(analyze_code_pair_local(a, b, max_skips = bad), "invalid skip budget")
fails(analyze_code_pair_local(a, b, window_statements = 21L), "bounded local recursion")
fails(analyze_code_pair_local(a, b, min_statements = 3L, window_statements = 2L), "ordered statement bounds")
fails(analyze_code_pair_local(a, b, max_statements = 1L), "total statement resource limit")
fails(analyze_code_pair_local(doc(copy), doc(copy), window_tokens = 3L, max_windows = 1L), "window resource limit")
fails(analyze_code_pair_local(doc(copy), doc(copy), window_tokens = 3L, max_candidates = 1L), "candidate resource limit")
fails(analyze_code_pair_local(doc(copy), doc(copy), window_tokens = 3L, max_seed_pairs = 1L), "seed-pair resource limit")
fails(analyze_code_pair_local(a, b, max_states = 1L), "local state resource limit")
fails(analyze_code_pair_local(a, b, max_token_work = 1L), "local token work resource limit")
fails(analyze_code_pair_local(doc(paste(copy, copy, sep = "\n")), doc(copy), min_tokens = 3L, min_statements = 2L, max_results = 1L), "local result resource limit")
fails(make_code_windows("bad"), "invalid statement table")
fails(prepare_code_statements("bad"), "invalid statement document")
cat("All", count, "code-local assertions passed.\n")
